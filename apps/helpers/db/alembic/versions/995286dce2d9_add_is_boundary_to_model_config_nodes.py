def _backfill(conn) -> None:
    """Mark as boundaries exactly the nodes the old spec-differs rule would have.

    Mirrors `DbClient.derive_training_targets`: walk each config's non-root nodes
    shallowest-first (a node's inherited spec depends on the boundaries above it) and
    call a node a boundary when its spec differs from the nearest boundary ancestor's,
    falling back to the root node's spec.
    """
    parent_of = {
        uuid: parent for uuid, parent in conn.exec_driver_sql("SELECT uuid, parent_uuid FROM labels").fetchall()
    }

    def depth(label_uuid):
        d, p = 0, parent_of.get(label_uuid)
        while p is not None:
            d += 1
            p = parent_of.get(p)
        return d

    rows = conn.exec_driver_sql(
        "SELECT uuid, model_config_uuid, label_uuid, model_type, architecture FROM model_config_nodes"
    ).fetchall()

    by_config: dict = {}
    for uuid, config_uuid, label_uuid, model_type, architecture in rows:
        by_config.setdefault(config_uuid, []).append((uuid, label_uuid, model_type, architecture))

    boundary_uuids: list[str] = []
    for nodes in by_config.values():
        root = next((n for n in nodes if n[1] is None), None)
        if root is None:
            continue
        root_spec = (root[2], root[3])
        boundary_spec: dict = {}

        for node_uuid, label_uuid, model_type, architecture in sorted(
            (n for n in nodes if n[1] is not None), key=lambda n: depth(n[1])
        ):
            ancestor, p = None, parent_of.get(label_uuid)
            while p is not None:
                if p in boundary_spec:
                    ancestor = p
                    break
                p = parent_of.get(p)
            inherited = boundary_spec[ancestor] if ancestor is not None else root_spec
            if (model_type, architecture) != inherited:
                boundary_spec[label_uuid] = (model_type, architecture)
                boundary_uuids.append(node_uuid)

    for node_uuid in boundary_uuids:
        conn.exec_driver_sql(
            "UPDATE model_config_nodes SET is_boundary = 1 WHERE uuid = ?",
            (node_uuid,),
        )


